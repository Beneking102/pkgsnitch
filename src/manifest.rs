//! Reads pinned versions from the dependency files of ecosystems pkgsnitch
//! does not run in its sandbox: PHP, Rust, Go, Ruby, .NET, Java and C++.
//! The `outdated` command compares these pins with their registries.

use serde::Serialize;
use serde_json::Value;

/// Where a package comes from, and so where its latest version is asked.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Registry {
    Npm,
    PyPI,
    Crates,
    Packagist,
    RubyGems,
    Go,
    NuGet,
    Maven,
    Vcpkg,
    Conan,
}

impl Registry {
    /// The name used in output and when asking the lookup script.
    pub fn id(self) -> &'static str {
        match self {
            Registry::Npm => "npm",
            Registry::PyPI => "pypi",
            Registry::Crates => "crates",
            Registry::Packagist => "packagist",
            Registry::RubyGems => "rubygems",
            Registry::Go => "go",
            Registry::NuGet => "nuget",
            Registry::Maven => "maven",
            Registry::Vcpkg => "vcpkg",
            Registry::Conan => "conan",
        }
    }
}

/// One pinned dependency.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Pinned {
    pub registry: Registry,
    pub name: String,
    pub version: String,
    /// Whether the project asks for it itself, where the file says so.
    pub direct: Option<bool>,
}

fn pin(registry: Registry, name: &str, version: &str, direct: Option<bool>) -> Pinned {
    Pinned {
        registry,
        name: name.to_string(),
        // Go and Composer write `v1.2.3`; registries answer without the `v`.
        version: version.trim_start_matches(['v', 'V']).to_string(),
        direct,
    }
}

/// The file names this module understands, besides `*.csproj`.
pub const FILES: [&str; 14] = [
    "composer.lock",
    "Cargo.lock",
    "go.mod",
    "Gemfile.lock",
    "packages.lock.json",
    "pom.xml",
    "gradle.lockfile",
    "build.gradle",
    "build.gradle.kts",
    "libs.versions.toml",
    "vcpkg.json",
    "conanfile.txt",
    "conan.lock",
    "Directory.Packages.props",
];

/// Parse a dependency file by its name, or `None` if the name is not one
/// of this module's.
pub fn read(file_name: &str, text: &str) -> Option<Vec<Pinned>> {
    Some(match file_name {
        "composer.lock" => composer(text),
        "Cargo.lock" => cargo(text),
        "go.mod" => go_mod(text),
        "Gemfile.lock" => gemfile(text),
        "packages.lock.json" => nuget_lock(text),
        "pom.xml" => pom(text),
        "gradle.lockfile" => gradle(text),
        "build.gradle" | "build.gradle.kts" => gradle_build(text),
        "libs.versions.toml" => version_catalog(text),
        "vcpkg.json" => vcpkg(text),
        "conanfile.txt" => conan_txt(text),
        "conan.lock" => conan_lock(text),
        "Directory.Packages.props" => package_tags(text, "<PackageVersion"),
        name if name.ends_with(".csproj") => package_tags(text, "<PackageReference"),
        _ => return None,
    })
}

/// Whether `text` is a `Cargo.lock`, which looks like Python's TOML locks.
pub fn is_cargo_lock(text: &str) -> bool {
    text.contains("generated by Cargo") || text.contains("source = \"registry+")
}

fn json(text: &str) -> Value {
    serde_json::from_str(text).unwrap_or(Value::Null)
}

/// PHP: `packages` and `packages-dev`, each with a name and a version.
fn composer(text: &str) -> Vec<Pinned> {
    let lock = json(text);
    ["packages", "packages-dev"]
        .iter()
        .filter_map(|section| lock.get(section)?.as_array())
        .flatten()
        .filter_map(|package| {
            let name = package.get("name")?.as_str()?;
            let version = package.get("version")?.as_str()?;
            // Branch aliases such as `dev-main` are not releases.
            version
                .trim_start_matches('v')
                .starts_with(|c: char| c.is_ascii_digit())
                .then(|| pin(Registry::Packagist, name, version, None))
        })
        .collect()
}

/// Rust: `[[package]]` tables; only those from the crates.io registry.
fn cargo(text: &str) -> Vec<Pinned> {
    let mut pins = Vec::new();
    fn value<'a>(line: &'a str, key: &str) -> Option<&'a str> {
        let rest = line.strip_prefix(key)?.trim_start().strip_prefix('=')?;
        Some(rest.trim().trim_matches('"'))
    }
    let (mut name, mut version, mut registry): (Option<&str>, Option<&str>, bool) =
        (None, None, false);
    // A closing sentinel flushes the last table.
    for line in text.lines().map(str::trim).chain(["["]) {
        if line.starts_with('[') {
            if let (Some(name), Some(version), true) = (name.take(), version.take(), registry) {
                pins.push(pin(Registry::Crates, name, version, None));
            }
            registry = false;
        } else if let Some(found) = value(line, "name") {
            name = Some(found);
        } else if let Some(found) = value(line, "version") {
            version = Some(found);
        } else if let Some(found) = value(line, "source") {
            registry = found.contains("crates.io-index");
        }
    }
    pins
}

/// Go: `require` lines, alone or in a block; `// indirect` marks the rest.
fn go_mod(text: &str) -> Vec<Pinned> {
    let mut pins = Vec::new();
    let mut block = false;
    for line in text.lines().map(str::trim) {
        let entry = if block {
            if line == ")" {
                block = false;
                continue;
            }
            line
        } else if line == "require (" {
            block = true;
            continue;
        } else if let Some(rest) = line.strip_prefix("require ") {
            rest
        } else {
            continue;
        };
        let mut words = entry.split_whitespace();
        if let (Some(module), Some(version)) = (words.next(), words.next()) {
            // `v0.0.0` is the placeholder of a module replaced by a local path.
            if version.starts_with('v') && version != "v0.0.0" {
                let direct = !entry.contains("// indirect");
                pins.push(pin(Registry::Go, module, version, Some(direct)));
            }
        }
    }
    pins
}

/// Ruby: the `specs:` of the GEM section, and DEPENDENCIES for what the
/// project asks for itself.
fn gemfile(text: &str) -> Vec<Pinned> {
    let mut specs: Vec<(String, String)> = Vec::new();
    let mut direct: Vec<String> = Vec::new();
    let mut section = "";
    for line in text.lines() {
        if !line.starts_with(' ') {
            section = line.trim();
            continue;
        }
        let indent = line.len() - line.trim_start().len();
        let entry = line.trim();
        if section == "GEM" && indent == 4 {
            if let Some((name, version)) = entry.split_once(" (") {
                // `1.16.0-x86_64-linux` is the same release for a platform.
                let version = version
                    .trim_end_matches(')')
                    .split('-')
                    .next()
                    .unwrap_or("");
                if !specs.iter().any(|(known, _)| known == name) {
                    specs.push((name.to_string(), version.to_string()));
                }
            }
        } else if section == "DEPENDENCIES" && indent == 2 {
            let name = entry.split([' ', '!']).next().unwrap_or(entry);
            direct.push(name.to_string());
        }
    }
    specs
        .iter()
        .map(|(name, version)| {
            pin(
                Registry::RubyGems,
                name,
                version,
                Some(direct.contains(name)),
            )
        })
        .collect()
}

/// .NET: `packages.lock.json`, grouped by target framework.
fn nuget_lock(text: &str) -> Vec<Pinned> {
    let lock = json(text);
    let mut pins: Vec<Pinned> = Vec::new();
    let frameworks = lock.get("dependencies").and_then(Value::as_object);
    for packages in frameworks
        .into_iter()
        .flatten()
        .filter_map(|(_, v)| v.as_object())
    {
        for (name, info) in packages {
            let kind = info.get("type").and_then(Value::as_str).unwrap_or("");
            let Some(version) = info.get("resolved").and_then(Value::as_str) else {
                continue;
            };
            // Projects of the same solution are not registry packages.
            if kind == "Project" || pins.iter().any(|p| &p.name == name && p.version == version) {
                continue;
            }
            pins.push(pin(Registry::NuGet, name, version, Some(kind == "Direct")));
        }
    }
    pins
}

/// .NET: `<PackageReference Include="X" Version="1.2.3" />` in a project
/// file, or `<PackageVersion ...>` where a solution pins versions centrally
/// in `Directory.Packages.props`.
fn package_tags(text: &str, tag: &str) -> Vec<Pinned> {
    text.split(tag)
        .skip(1)
        .filter_map(|rest| {
            let tag = &rest[..rest.find('>')?];
            let name = attribute(tag, "Include")?;
            let version = attribute(tag, "Version")?;
            version
                .starts_with(|c: char| c.is_ascii_digit())
                .then(|| pin(Registry::NuGet, name, version, Some(true)))
        })
        .collect()
}

fn attribute<'a>(tag: &'a str, name: &str) -> Option<&'a str> {
    let rest = &tag[tag.find(&format!("{name}=\""))? + name.len() + 2..];
    Some(&rest[..rest.find('"')?])
}

/// Java: `<dependency>` elements with a version, written out or as a
/// `${property}` defined in the same file. Versions inherited from a parent
/// or a BOM are not in the file and cannot be read from it.
fn pom(text: &str) -> Vec<Pinned> {
    let properties = pom_properties(text);
    let mut pins: Vec<Pinned> = Vec::new();
    for rest in text.split("<dependency>").skip(1) {
        let Some(end) = rest.find("</dependency>") else {
            continue;
        };
        let element = &rest[..end];
        let (Some(group), Some(artifact), Some(version)) = (
            tag(element, "groupId"),
            tag(element, "artifactId"),
            tag(element, "version"),
        ) else {
            continue;
        };
        let version = version
            .strip_prefix("${")
            .and_then(|name| name.strip_suffix('}'))
            .and_then(|name| properties.iter().find(|(key, _)| *key == name))
            .map_or(version, |(_, value)| value);
        let name = format!("{group}:{artifact}");
        let known = pins.iter().any(|p| p.name == name && p.version == version);
        if version.starts_with(|c: char| c.is_ascii_digit()) && !known {
            pins.push(pin(Registry::Maven, &name, version, Some(true)));
        }
    }
    pins
}

/// The `<properties>` of a pom as name and value.
fn pom_properties(text: &str) -> Vec<(&str, &str)> {
    let Some(start) = text.find("<properties>") else {
        return Vec::new();
    };
    let body = &text[start + "<properties>".len()..];
    let body = &body[..body.find("</properties>").unwrap_or(body.len())];
    let mut found = Vec::new();
    let mut rest = body;
    while let Some(open) = rest.find('<') {
        rest = &rest[open + 1..];
        let Some(close) = rest.find('>') else { break };
        let name = &rest[..close];
        rest = &rest[close + 1..];
        // Comments, closing tags and empty elements hold no value.
        if name.starts_with(['/', '!', '?']) || name.ends_with('/') || name.contains(' ') {
            continue;
        }
        if let Some(end) = rest.find(&format!("</{name}>")) {
            found.push((name, rest[..end].trim()));
            rest = &rest[end..];
        }
    }
    found
}

/// Java: dependency notations in a Gradle build file, `"group:artifact:1.2.3"`.
/// Versions computed in the build script are not literals and are skipped.
fn gradle_build(text: &str) -> Vec<Pinned> {
    let mut pins: Vec<Pinned> = Vec::new();
    for quote in ['"', '\''] {
        // Every second piece of a line split at quotes lies inside a string.
        for line in text
            .lines()
            .filter(|line| !line.trim_start().starts_with("//"))
        {
            for literal in line.split(quote).skip(1).step_by(2) {
                if let Some(found) = coordinate(literal) {
                    if !pins.contains(&found) {
                        pins.push(found);
                    }
                }
            }
        }
    }
    pins
}

/// `group:artifact:version` with a literal version, as a Maven pin.
fn coordinate(text: &str) -> Option<Pinned> {
    let mut parts = text.split(':');
    let (group, artifact, version) = (parts.next()?, parts.next()?, parts.next()?);
    let plain = |s: &str| !s.is_empty() && !s.contains([' ', '$', '/', '{']);
    (parts.next().is_none()
        && plain(group)
        && plain(artifact)
        && plain(version)
        && group.contains(|c: char| c.is_ascii_alphabetic())
        && version.starts_with(|c: char| c.is_ascii_digit()))
    .then(|| {
        pin(
            Registry::Maven,
            &format!("{group}:{artifact}"),
            version,
            Some(true),
        )
    })
}

/// Java: a Gradle version catalog (`libs.versions.toml`). Libraries name a
/// module and either a version or a reference into `[versions]`.
fn version_catalog(text: &str) -> Vec<Pinned> {
    fn quoted<'a>(line: &'a str, key: &str) -> Option<&'a str> {
        let rest = &line[line.find(key)? + key.len()..];
        let rest = rest
            .trim_start()
            .strip_prefix('=')?
            .trim_start()
            .strip_prefix('"')?;
        Some(&rest[..rest.find('"')?])
    }
    let mut versions: Vec<(&str, &str)> = Vec::new();
    let mut pins: Vec<Pinned> = Vec::new();
    let mut section = "";
    // Versions first, whatever the order of the tables.
    for pass in ["[versions]", "[libraries]"] {
        for line in text.lines().map(str::trim) {
            if line.starts_with('[') {
                section = line;
                continue;
            }
            if section != pass || line.starts_with('#') {
                continue;
            }
            let Some((key, value)) = line.split_once('=') else {
                continue;
            };
            let (key, value) = (key.trim(), value.trim());
            if pass == "[versions]" {
                if let Some(version) = value.strip_prefix('"').and_then(|v| v.strip_suffix('"')) {
                    versions.push((key, version));
                }
                continue;
            }
            // `name = "group:artifact:1.2.3"`
            if let Some(found) = value
                .strip_prefix('"')
                .and_then(|v| coordinate(v.trim_end_matches('"')))
            {
                pins.push(found);
                continue;
            }
            let module = quoted(line, "module").map(str::to_string).or_else(|| {
                Some(format!(
                    "{}:{}",
                    quoted(line, "group")?,
                    quoted(line, "name")?
                ))
            });
            let version = quoted(line, "version.ref")
                .and_then(|name| versions.iter().find(|(key, _)| *key == name))
                .map(|(_, version)| *version)
                .or_else(|| quoted(line, "version"));
            if let (Some(module), Some(version)) = (module, version) {
                if version.starts_with(|c: char| c.is_ascii_digit()) {
                    pins.push(pin(Registry::Maven, &module, version, Some(true)));
                }
            }
        }
    }
    pins
}

fn tag<'a>(element: &'a str, name: &str) -> Option<&'a str> {
    let open = format!("<{name}>");
    let rest = &element[element.find(&open)? + open.len()..];
    Some(rest[..rest.find(&format!("</{name}>"))?].trim())
}

/// Java: Gradle's lockfile, `group:artifact:version=configurations`.
fn gradle(text: &str) -> Vec<Pinned> {
    text.lines()
        .filter(|line| !line.starts_with('#'))
        .filter_map(|line| {
            let coordinate = line.split('=').next()?;
            let (name, version) = coordinate.rsplit_once(':')?;
            name.contains(':')
                .then(|| pin(Registry::Maven, name, version, None))
        })
        .collect()
}

/// C++: vcpkg manifests pin with `version>=` and with `overrides`.
fn vcpkg(text: &str) -> Vec<Pinned> {
    let manifest = json(text);
    let entries = |section: &str, field: &'static str| {
        let list = manifest
            .get(section)
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        list.into_iter().filter_map(move |entry| {
            let name = entry.get("name")?.as_str()?.to_string();
            let version = entry.get(field)?.as_str()?.to_string();
            // `1.3.1#2` carries a port revision after the `#`.
            let version = version.split('#').next().unwrap_or("").to_string();
            Some(pin(Registry::Vcpkg, &name, &version, Some(true)))
        })
    };
    let mut pins: Vec<Pinned> = entries("overrides", "version").collect();
    for found in entries("dependencies", "version>=") {
        if !pins.iter().any(|p| p.name == found.name) {
            pins.push(found);
        }
    }
    pins
}

/// C++: `[requires]` of a conanfile.txt, `name/version[@user/channel]`.
fn conan_txt(text: &str) -> Vec<Pinned> {
    let mut pins = Vec::new();
    let mut section = "";
    for line in text.lines().map(str::trim) {
        if line.starts_with('[') {
            section = line;
        } else if matches!(
            section,
            "[requires]" | "[tool_requires]" | "[build_requires]"
        ) {
            pins.extend(conan_reference(line, section == "[requires]"));
        }
    }
    pins
}

/// C++: the `requires` lists of a conan.lock, `name/version#revision`.
fn conan_lock(text: &str) -> Vec<Pinned> {
    let lock = json(text);
    ["requires", "build_requires"]
        .iter()
        .filter_map(|section| lock.get(section)?.as_array())
        .flatten()
        .filter_map(Value::as_str)
        .filter_map(|reference| conan_reference(reference, true))
        .collect()
}

fn conan_reference(reference: &str, direct: bool) -> Option<Pinned> {
    let reference = reference.split(['#', '@', '%']).next()?.trim();
    let (name, version) = reference.split_once('/')?;
    // `[>=1.2 <2]` is a range, not a pin.
    version
        .starts_with(|c: char| c.is_ascii_digit())
        .then(|| pin(Registry::Conan, name, version, Some(direct)))
}

