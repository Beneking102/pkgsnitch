    #[test]
    fn reads_java_files() {
        let pom = "<project>\n  <dependencies>\n    <dependency>\n      <groupId>com.google.guava</groupId>\n      <artifactId>guava</artifactId>\n      <version>33.0.0-jre</version>\n    </dependency>\n    <dependency>\n      <groupId>org.slf4j</groupId>\n      <artifactId>slf4j-api</artifactId>\n      <version>${slf4j.version}</version>\n    </dependency>\n    <dependency>\n      <groupId>managed</groupId>\n      <artifactId>by-parent</artifactId>\n    </dependency>\n  </dependencies>\n</project>\n";
        assert_eq!(
            found("pom.xml", pom),
            [entry("com.google.guava:guava", "33.0.0-jre", Some(true))]
        );
        let gradle = "# This is a Gradle generated file for dependency locking.\ncom.google.guava:guava:33.0.0-jre=compileClasspath,runtimeClasspath\norg.slf4j:slf4j-api:2.0.13=runtimeClasspath\nempty=annotationProcessor\n";
        assert_eq!(
            found("gradle.lockfile", gradle),
            [
                entry("com.google.guava:guava", "33.0.0-jre", None),
                entry("org.slf4j:slf4j-api", "2.0.13", None)
            ]
        );
    }

    #[test]
    fn reads_cpp_files() {
        let vcpkg = r#"{"name":"app","dependencies":["zlib",{"name":"fmt","version>=":"10.1.0"},{"name":"curl","version>=":"8.0.0"}],"overrides":[{"name":"curl","version":"8.4.0#1"}]}"#;
        assert_eq!(
            found("vcpkg.json", vcpkg),
            [
                entry("curl", "8.4.0", Some(true)),
                entry("fmt", "10.1.0", Some(true))
            ]
        );
        let conanfile = "[requires]\nzlib/1.3.1\nfmt/10.2.1@user/stable\nboost/[>=1.80 <2]\n\n[tool_requires]\ncmake/3.28.1\n\n[generators]\nCMakeDeps\n";
        assert_eq!(
            found("conanfile.txt", conanfile),
            [
                entry("zlib", "1.3.1", Some(true)),
                entry("fmt", "10.2.1", Some(true)),
                entry("cmake", "3.28.1", Some(false))
            ]
        );
        let lock = r##"{"version":"0.5","requires":["zlib/1.3.1#f52e03ae3d251dec704634230cd806a2%1708593606.497"],"build_requires":["cmake/3.28.1#abc"]}"##;
        assert_eq!(
            found("conan.lock", lock),
            [
                entry("zlib", "1.3.1", Some(true)),
                entry("cmake", "3.28.1", Some(true))
            ]
        );
    }

