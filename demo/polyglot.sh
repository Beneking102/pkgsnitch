#!/bin/sh
# Writes a small project that pins old versions in ten ecosystems, to try
# `pkgsnitch outdated` on:
#
#   sh demo/polyglot.sh /tmp/polyglot && pkgsnitch outdated /tmp/polyglot
#
# The files are generated rather than checked in, so that the old versions
# they name do not show up as dependencies of this repository.
set -eu
dir="${1:?usage: polyglot.sh <directory>}"
mkdir -p "$dir"
cd "$dir"

cat > package-lock.json <<'EOF'
{
  "name": "polyglot",
  "lockfileVersion": 3,
  "packages": {
    "": { "name": "polyglot", "dependencies": { "left-pad": "^1.2.0", "lodash": "^4.17.20" } },
    "node_modules/left-pad": { "version": "1.2.0" },
    "node_modules/lodash": { "version": "4.17.20" }
  }
}
EOF

cat > requirements.txt <<'EOF'
requests==2.31.0
idna==3.6
EOF

cat > composer.lock <<'EOF'
{
  "packages": [
    { "name": "symfony/console", "version": "v6.4.0" },
    { "name": "psr/log", "version": "3.0.0" }
  ],
  "packages-dev": []
}
EOF

cat > Cargo.lock <<'EOF'
# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "serde"
version = "1.0.150"
source = "registry+https://github.com/rust-lang/crates.io-index"
EOF

cat > go.mod <<'EOF'
module example.com/polyglot

go 1.22

require (
	github.com/gin-gonic/gin v1.9.0
	golang.org/x/text v0.14.0 // indirect
)
EOF

cat > Gemfile.lock <<'EOF'
GEM
  remote: https://rubygems.org/
  specs:
    rake (13.0.6)

DEPENDENCIES
  rake
EOF

cat > App.csproj <<'EOF'
<Project Sdk="Microsoft.NET.Sdk">
  <ItemGroup>
    <PackageReference Include="Newtonsoft.Json" Version="12.0.3" />
  </ItemGroup>
</Project>
EOF

cat > pom.xml <<'EOF'
<project>
  <dependencies>
    <dependency>
      <groupId>org.slf4j</groupId>
      <artifactId>slf4j-api</artifactId>
      <version>1.7.36</version>
    </dependency>
  </dependencies>
</project>
EOF

cat > vcpkg.json <<'EOF'
{
  "name": "polyglot",
  "dependencies": [ { "name": "fmt", "version>=": "9.1.0" } ]
}
EOF

cat > conanfile.txt <<'EOF'
[requires]
zlib/1.2.13
EOF

echo "wrote $(ls | wc -l) dependency files to $dir"
